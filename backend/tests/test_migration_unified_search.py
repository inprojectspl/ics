"""Existing rows are reindexed by 0044; downgrade restores the old config."""

import asyncio
import os
from uuid import uuid4

import asyncpg

from tests.test_schema_drift import _alembic, _recreate


async def seed(url):
    conn = await asyncpg.connect(url.replace("postgresql+asyncpg://", "postgresql://"))
    owner, asset = uuid4(), uuid4()
    try:
        await conn.execute(
            "INSERT INTO users (id, email) VALUES ($1, $2)", owner, f"{owner}@example.com"
        )
        await conn.execute(
            "INSERT INTO assets (id, owner_id, slug, title, kind, storage_prefix) "
            "VALUES ($1, $2, $3::text, 'Żółta gęś', 'md_single', $3::text)",
            asset,
            owner,
            asset.hex,
        )
    finally:
        await conn.close()
    return asset


async def check(url, asset, *, upgraded):
    conn = await asyncpg.connect(url.replace("postgresql+asyncpg://", "postgresql://"))
    try:
        config = "public.ics_search" if upgraded else "simple"
        found = await conn.fetchval(
            "SELECT search_tsv @@ to_tsquery($1::regconfig, 'zolta:*') FROM assets WHERE id=$2",
            config,
            asset,
        )
        assert found is upgraded
        assert await conn.fetchval(
            "SELECT 1 FROM pg_indexes WHERE indexname='ix_assets_search_tsv'"
        )
        assert (
            bool(await conn.fetchval("SELECT 1 FROM pg_ts_config WHERE cfgname='ics_search'"))
            is upgraded
        )
        if upgraded:
            # The trigger is generated by PostgreSQL, with no application job.
            await conn.execute("UPDATE assets SET summary='Łódź' WHERE id=$1", asset)
            assert await conn.fetchval(
                "SELECT search_tsv @@ to_tsquery('public.ics_search', 'lodz:*') FROM assets WHERE id=$1",
                asset,
            )
    finally:
        await conn.close()


def test_upgrade_reindexes_existing_rows_and_downgrade_restores_config():
    base = os.environ["ICS_DATABASE_URL"]
    name = f"ics_unified_search_{os.environ.get('PYTEST_XDIST_WORKER', 'master')}"
    url = base.rsplit("/", 1)[0] + f"/{name}"
    asyncio.run(_recreate(base, name))
    result = _alembic("upgrade", "0043", url=url)
    assert result.returncode == 0, result.stderr
    asset = asyncio.run(seed(url))
    result = _alembic("upgrade", "0044", url=url)
    assert result.returncode == 0, result.stderr
    asyncio.run(check(url, asset, upgraded=True))
    result = _alembic("downgrade", "0043", url=url)
    assert result.returncode == 0, result.stderr
    asyncio.run(check(url, asset, upgraded=False))
