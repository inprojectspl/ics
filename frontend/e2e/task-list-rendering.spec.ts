/**
 * E2E layout test for task lists: `- [ ] **Label** value`.
 *
 * Uses real backend HTML with bold-prefixed items. A `flex` layout on
 * <li.task-list-item> turns the inline children (checkbox, <strong>, text
 * node) into separate flex items, splitting label and value into two narrow
 * columns that each wrap onto 2-3 lines. The checkbox is absolutely
 * positioned instead, and the rest flows like a paragraph with a hanging
 * indent.
 *
 * Requires the dev server on :5174 (E2E_BASE_URL).
 */
import { test, expect } from "@playwright/test";

// Production MarkdownView shell from the helper, not a frozen markup copy.
import { mountMarkdownBody } from "./helpers/mountMarkdown";

// HTML generated by the backend (markdown-it-py + tasklists_plugin).
const TASK_LIST_HTML = `
<ul class="contains-task-list">
  <li class="task-list-item enabled"><input class="task-list-item-checkbox" type="checkbox"> <strong>Structure decision</strong>: one "Northwind Rollout" project with two Versions per region, or two separate projects? (recommendation: one project, identical stack)</li>
  <li class="task-list-item enabled"><input class="task-list-item-checkbox" type="checkbox"> <strong>Epics</strong> = fixed sections of the scope document (Inception, Hardware, Software, Integration, Training, Post-deployment Support, …)</li>
  <li class="task-list-item enabled"><input class="task-list-item-checkbox" type="checkbox"> <strong>Milestones</strong> = M1\u2013M8 from the scope document with <strong>fixed contractual dates and a "late delivery penalty" flag</strong> (input from Phase 1)</li>
  <li class="task-list-item enabled"><input class="task-list-item-checkbox" type="checkbox"> Every Epic <strong>links to its source document</strong> in shared storage (scope, proposal, terms), so there is always a reference</li>
  <li class="task-list-item enabled"><input class="task-list-item-checkbox" type="checkbox"> Custom field e.g. <code>clause ref</code> on contractually sensitive tasks (penalties, deadlines, deliverables)</li>
</ul>
`;

async function mountTaskList(page: import("@playwright/test").Page) {
  await mountMarkdownBody(page, TASK_LIST_HTML);
}

test.describe("task list rendering", () => {
  test("the bold label stays next to its value (inline flow)", async ({ page }) => {
    await mountTaskList(page);

    // `<strong>` must share a line with the text node after it
    // (`: one project...`), not wrap independently in its own flex item.
    const firstItem = page.locator("li.task-list-item").first();
    const strongBox = await firstItem.locator("strong").first().boundingBox();
    expect(strongBox).not.toBeNull();

    // The first <li> should stay under 4 lines of body text (about 28px each
    // at text-body=17px, lh=1.65); this prompt should take at most 3.
    const liBox = await firstItem.boundingBox();
    expect(liBox).not.toBeNull();
    expect(liBox!.height).toBeLessThan(28 * 4);

    // The checkbox is absolutely positioned on the left, so its X is smaller
    // than the strong's, which sits in the content area after padding-left.
    const checkbox = firstItem.locator("input[type='checkbox']");
    const cbBox = await checkbox.boundingBox();
    expect(cbBox).not.toBeNull();
    expect(cbBox!.x).toBeLessThan(strongBox!.x);

    const cbPosition = await checkbox.evaluate((el) => window.getComputedStyle(el).position);
    expect(cbPosition).toBe("absolute");
  });

  test("every <li> renders in normal flow (no flex split)", async ({ page }) => {
    await mountTaskList(page);

    // All task-list items stack vertically (Y increases monotonically).
    const ys = await page
      .locator("li.task-list-item")
      .evaluateAll((els) => els.map((el) => el.getBoundingClientRect().top));
    expect(ys.length).toBe(5);
    for (let i = 1; i < ys.length; i++) {
      const prev = ys[i - 1] ?? 0;
      const curr = ys[i] ?? 0;
      expect(curr).toBeGreaterThan(prev);
    }

    // A flex <li> is what breaks the inline flow.
    const liDisplay = await page
      .locator("li.task-list-item")
      .first()
      .evaluate((el) => window.getComputedStyle(el).display);
    expect(liDisplay).not.toBe("flex");
    expect(liDisplay).not.toBe("inline-flex");

    await page.screenshot({ path: "test-results/task-list.png", fullPage: true });
  });
});
